import { useRef, useState } from 'react'
import { Link, useParams } from 'react-router-dom'
import { useQuery } from '@tanstack/react-query'
import { QRCodeSVG } from 'qrcode.react'
import { toPng } from 'html-to-image'
import { CalendarDays, CheckCircle2, Download, MapPin } from 'lucide-react'
import { format } from 'date-fns'
import { getPassByCode, passQrValue, passQueryKeys } from '../services/passes'
import { formatRegistrantName, formatRoleLabel } from '../utils/passes'
import { isSupabaseConfigured } from '../lib/supabase'
import { useDocumentMeta } from '../hooks/useDocumentMeta'
import { SITE_URL } from '../config/site'

export default function EventPassPage() {
  const { code = '' } = useParams()
  const cardRef = useRef<HTMLDivElement>(null)
  const darkRef = useRef<HTMLDivElement>(null)
  const [saving, setSaving] = useState(false)
  const [message, setMessage] = useState('')

  const passQuery = useQuery({
    queryKey: passQueryKeys.pass(code),
    queryFn: () => getPassByCode(code),
    enabled: isSupabaseConfigured && Boolean(code),
    retry: false,
  })
  const pass = passQuery.data
  const event = pass?.pov_events
  const brand = event?.pass_brand_label || 'POV'

  useDocumentMeta(pass ? `Event pass · ${formatRegistrantName(pass.family_name, pass.first_name)}` : 'Event pass')

  const savePhoto = async () => {
    const node = darkRef.current || cardRef.current
    if (!node || !pass) return
    setSaving(true)
    setMessage('')
    try {
      const dataUrl = await toPng(node, { cacheBust: true, pixelRatio: 2, backgroundColor: '#0b0b0c' })
      const link = document.createElement('a')
      link.download = `${pass.pass_code}-pass.png`
      link.href = dataUrl
      link.click()
      setMessage('Pass image saved. Check your downloads or Photos.')
    } catch {
      setMessage('Unable to save the image on this device. Take a screenshot of your pass instead.')
    } finally {
      setSaving(false)
    }
  }

  if (passQuery.isLoading) return <div className="px-5 py-8"><div className="skeleton h-40 rounded-3xl" /><div className="skeleton mt-4 h-80 rounded-3xl" /></div>
  if (!pass || !event) {
    return <div className="px-5 py-12 text-center">
      <h1 className="text-2xl font-black">Pass not found</h1>
      <p className="mt-2 text-sm text-neutral-500">Check the code or register again from the event page.</p>
      <Link to="/events" className="mt-4 inline-block font-bold text-orange-600">Browse events</Link>
    </div>
  }

  const qrValue = passQrValue(pass.pass_code)
  const displayName = formatRegistrantName(pass.family_name, pass.first_name)
  const meta = `${formatRoleLabel(pass.role)}${pass.city ? ` · ${pass.city}` : ''}`
  const checkedIn = pass.status === 'checked_in' || Boolean(pass.checked_in_at)

  return (
    <div className="bg-white px-5 pb-12 pt-6">
      <section className="rounded-2xl border border-orange-200 p-4">
        <p className="text-[10px] font-bold uppercase tracking-[.16em] text-orange-500">{event.registration_status_label || 'Upcoming event'}</p>
        <h1 className="mt-2 text-[22px] font-black uppercase tracking-tight">{event.title}</h1>
        <p className="mt-3 flex items-start gap-2 text-sm text-neutral-600"><CalendarDays size={16} className="mt-0.5 shrink-0 text-orange-500" />{format(new Date(event.start_date), 'EEE, MMM d, yyyy, h:mm a')}</p>
        {event.location && <p className="mt-2 flex items-start gap-2 text-sm uppercase text-neutral-600"><MapPin size={16} className="mt-0.5 shrink-0 text-orange-500" />{event.location}</p>}
      </section>

      <div className="mt-4 flex items-center gap-3 rounded-2xl border border-orange-100 bg-orange-50/60 px-4 py-3">
        <span className="grid size-8 place-items-center rounded-full bg-orange-500 text-white"><CheckCircle2 size={18} /></span>
        <p className="text-sm font-semibold text-neutral-800">
          {checkedIn
            ? `Checked in · ${event.title}`
            : `Registered · POV QR ready for entrance confirmation`}
        </p>
      </div>

      <div ref={cardRef} className="mt-5 overflow-hidden rounded-2xl border border-orange-300 bg-white">
        <div className="bg-orange-500 px-4 py-3 text-center text-sm font-black uppercase tracking-[.18em] text-white">Your confirmation QR</div>
        <div className="px-5 py-6 text-center">
          <p className="text-sm font-black uppercase tracking-[.18em] text-orange-500">{brand}</p>
          <p className="mt-2 text-xs text-neutral-500">Generated by Pinoy Online Venture</p>
          <div className="mx-auto mt-5 grid w-fit place-items-center rounded-xl bg-white p-3">
            <QRCodeSVG value={qrValue} size={196} level="M" includeMargin={false} />
          </div>
          <h2 className="mt-5 text-[22px] font-black uppercase tracking-tight">{displayName}</h2>
          <p className="mt-1 text-sm text-neutral-500">{meta}</p>
          <p className="mt-4 text-lg font-black uppercase tracking-wide text-orange-500">{pass.pass_code}</p>
          <p className="mt-3 text-xs leading-5 text-neutral-500">Show this QR to staff at the entrance for confirmation / check-in.</p>
        </div>
      </div>

      {/* Off-screen dark pass used for Save to Photos export */}
      <div className="pointer-events-none fixed left-[-9999px] top-0" aria-hidden>
        <div ref={darkRef} className="w-[360px] bg-[#0b0b0c] px-8 py-10 text-center text-white">
          <p className="text-4xl font-black tracking-tight text-orange-500">{brand}</p>
          <p className="mt-1 text-sm font-bold uppercase tracking-[.22em] text-white">Event pass</p>
          <div className="mx-auto mt-8 grid w-fit place-items-center rounded-xl bg-white p-4">
            <QRCodeSVG value={qrValue} size={220} level="M" includeMargin={false} />
          </div>
          <h2 className="mt-8 text-2xl font-black uppercase tracking-tight">{displayName}</h2>
          <p className="mt-2 text-sm text-neutral-300">{meta}</p>
          <p className="mt-5 text-2xl font-black uppercase tracking-wide text-orange-500">{pass.pass_code}</p>
          <p className="mt-8 text-xs text-neutral-400">Show this QR to the usher at the entrance</p>
          <p className="mt-2 text-xs text-neutral-500">{SITE_URL?.replace(/^https?:\/\//, '') || 'pinoyonlineventure'}</p>
        </div>
      </div>

      <button
        type="button"
        onClick={() => void savePhoto()}
        disabled={saving}
        className="focus-ring mt-5 inline-flex min-h-12 w-full items-center justify-center gap-2 rounded-2xl bg-orange-500 font-bold text-white disabled:opacity-60"
      >
        <Download size={18} />{saving ? 'Saving…' : 'Save to Photos'}
      </button>
      {message && <p className="mt-3 text-center text-sm text-neutral-600">{message}</p>}

      <div className="mt-6 text-center text-sm">
        <Link to={event.slug ? `/events/${event.slug}` : '/events'} className="font-semibold text-orange-600 underline underline-offset-2">Back to event</Link>
      </div>
    </div>
  )
}
